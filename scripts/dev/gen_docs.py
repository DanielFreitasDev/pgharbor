#!/usr/bin/env python3
"""Generate the tool reference from the tool registry.

    python scripts/dev/gen_docs.py            rewrite docs/tools.md and the README tables
    python scripts/dev/gen_docs.py --check    fail if they are out of date (used by tests)

The registry is the single source of truth: names, groups and descriptions in the
documentation are never typed by hand.
"""

from __future__ import annotations

import inspect
import re
import sys
import types
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from pgharbor.app import REGISTRY, ToolSpec  # noqa: E402
from pgharbor.server import load_tool_modules  # noqa: E402

GROUPS = {
    "core": ("Core", "Connections, guarded queries and plans."),
    "schema": ("Schema", "Find your way around: objects, definitions, DDL, dependencies."),
    "data": ("Data", "Look at rows and column statistics, through the guarded path."),
    "performance": ("Performance", "What the server is doing and where time and space go."),
    "health": ("Health", "Check-ups, index advice, settings, sequences, WAL."),
    "replication": ("Replication", "Standbys, slots, publications and subscriptions."),
    "security": ("Security", "Roles, privileges, audits. Never returns a secret."),
    "extensions": ("Extensions", "Installed extensions and what they add; integrity checks."),
    "admin": ("Administration", "Change the database. Only on connections configured for it, "
                                "always confirmed by the user."),
}  # fmt: skip
START = "<!-- tools:start -->"
END = "<!-- tools:end -->"


def specs() -> list[ToolSpec]:
    load_tool_modules()
    return [spec for spec in REGISTRY.values() if spec.group in GROUPS]


def first_sentence(spec: ToolSpec) -> str:
    """The lead of a description, short enough for a table cell."""
    text = " ".join(spec.description.split())
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = (match.group(1) if match else text).strip()
    if len(sentence) > 170 and ": " in sentence:
        # "Do X and report Y: a, b, c, ..." -> keep the claim, drop the enumeration.
        sentence = sentence.split(": ", 1)[0] + "."
    if len(sentence) > 230:
        sentence = sentence[:227].rsplit(" ", 1)[0] + "..."
    return sentence


def type_name(annotation: object) -> str:
    if annotation is inspect.Parameter.empty:
        return ""
    origin = typing.get_origin(annotation)
    if origin is typing.Literal:
        return " \\| ".join(f'`"{a}"`' for a in typing.get_args(annotation))
    if origin is typing.Annotated:
        return ""
    text = getattr(annotation, "__name__", None)
    if origin is None and text:
        return f"`{text}`"
    return "`" + _render(annotation).replace("|", "\\|") + "`"


def _render(annotation: object) -> str:
    """A type as text, built from its structure. ``str(annotation)`` cannot be used: the
    same annotation prints as ``Optional[...]`` or ``... | None`` depending on the Python
    version, and the generated reference must be the same on all of them."""
    if annotation is None or annotation is type(None):
        return "None"
    origin = typing.get_origin(annotation)
    arguments = typing.get_args(annotation)
    if origin is typing.Literal:
        return " | ".join(repr(a) for a in arguments)
    if origin is typing.Union or origin is types.UnionType:
        return " | ".join(_render(a) for a in arguments)
    if origin is typing.Annotated:
        return _render(arguments[0])
    if origin is not None:
        name = getattr(origin, "__name__", None) or str(origin).replace("typing.", "")
        return f"{name}[{', '.join(_render(a) for a in arguments)}]" if arguments else name
    return getattr(annotation, "__name__", None) or str(annotation).replace("typing.", "")


def parameters(spec: ToolSpec) -> list[tuple[str, str, str]]:
    out = []
    signature = inspect.signature(spec.function)
    hints = typing.get_type_hints(inspect.unwrap(spec.function), include_extras=True)
    for name, parameter in signature.parameters.items():
        annotation = hints.get(name, parameter.annotation)
        if typing.get_origin(annotation) is typing.Annotated:
            continue  # filled by the framework (confirmation dialogs), not by the caller
        default = (
            "required" if parameter.default is inspect.Parameter.empty else repr(parameter.default)
        )
        out.append((name, type_name(annotation), default))
    return out


def reference() -> str:
    all_specs = specs()
    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/dev/gen_docs.py from the tool registry. Do not edit. -->",
        "",
        f"pgharbor exposes **{len(all_specs)} tools** in {len(GROUPS)} groups. Every tool takes a",
        "`connection` (a name from `pg_connections`); with a single configured connection it",
        "may be left out. Tools adapt to the PostgreSQL version of the server (9.6 to 19).",
        "",
        "Tools that write are listed only when some connection allows writing.",
        "",
    ]
    for group, (title, _blurb) in GROUPS.items():
        members = [s for s in all_specs if s.group == group]
        if members:
            anchor = title.lower().replace(" ", "-")
            lines.append(f"- [{title}](#{anchor}) ({len(members)}): " + ", ".join(
                f"`{s.name}`" for s in members))  # fmt: skip
    lines.append("")
    for group, (title, blurb) in GROUPS.items():
        members = [s for s in all_specs if s.group == group]
        if not members:
            continue
        lines += [f"## {title}", "", blurb, ""]
        for spec in members:
            flags = []
            if spec.writes:
                flags.append(f"writes; needs access `{spec.minimum_access.value}`")
            lines += [f"### `{spec.name}`", ""]
            if flags:
                lines += [f"*{'; '.join(flags)}*", ""]
            lines += [spec.description, ""]
            rows = parameters(spec)
            if rows:
                lines += ["| Parameter | Type | Default |", "|---|---|---|"]
                lines += [f"| `{n}` | {t} | {d if d == 'required' else f'`{d}`'} |"
                          for n, t, d in rows]  # fmt: skip
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def readme_tables() -> str:
    all_specs = specs()
    lines = [START, ""]
    for group, (title, blurb) in GROUPS.items():
        members = [s for s in all_specs if s.group == group]
        if not members:
            continue
        lines += [
            "<details>",
            f"<summary><b>{title}</b> · {len(members)} tool{'s' if len(members) != 1 else ''}"
            f" · {blurb}</summary>",
            "",
            "| Tool | What it does |",
            "|---|---|",
        ]
        lines += [f"| `{s.name}` | {first_sentence(s)} |" for s in members]
        lines += ["", "</details>", ""]
    lines.append(END)
    return "\n".join(lines)


def patched(path: Path, block: str) -> str:
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{path} has no {START} ... {END} block")
    head, rest = text.split(START, 1)
    _old, tail = rest.split(END, 1)
    return head + block + tail


def main() -> int:
    check = "--check" in sys.argv
    targets = {ROOT / "docs" / "tools.md": reference()}
    for readme in (ROOT / "README.md", ROOT / "README.pt-BR.md"):
        if readme.exists() and START in readme.read_text(encoding="utf-8"):
            targets[readme] = patched(readme, readme_tables())
    stale = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            stale.append(path)
            if not check:
                path.write_text(content, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
    if check and stale:
        print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("run: python scripts/dev/gen_docs.py")
        return 1
    print(f"{len(specs())} tools documented")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
